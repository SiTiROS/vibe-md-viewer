//! RichEdit wrapper (msftedit.dll ships with Windows, nothing needs to be installed).

use windows::core::{Interface, PCWSTR, PWSTR};
use windows::Win32::Foundation::{HWND, POINT, POINTL, RECT};
use windows::Win32::System::LibraryLoader::{GetModuleHandleW, LoadLibraryExW, LOAD_LIBRARY_SEARCH_SYSTEM32};
use windows::Win32::UI::Controls::RichEdit::*;
use windows::Win32::UI::Controls::{
    EM_CHARFROMPOS, EM_EMPTYUNDOBUFFER, EM_GETRECT, EM_LINEINDEX, EM_LINELENGTH, EM_POSFROMCHAR,
    EM_REPLACESEL, EM_SCROLLCARET, EM_SETREADONLY, EM_SETRECT,
};
use windows::Win32::UI::WindowsAndMessaging::{
    CreateWindowExW, GetClientRect, ES_AUTOVSCROLL, ES_MULTILINE, ES_NOHIDESEL, ES_READONLY, HMENU,
    WINDOW_EX_STYLE, WINDOW_STYLE, WS_CHILD, WS_CLIPSIBLINGS, WS_TABSTOP, WS_VSCROLL,
};

use crate::util::{send, wide};

pub fn load_library() -> bool {
    let name = wide("msftedit.dll");
    unsafe { LoadLibraryExW(PCWSTR::from_raw(name.as_ptr()), None, LOAD_LIBRARY_SEARCH_SYSTEM32).is_ok() }
}

pub fn create(parent: HWND, id: usize, readonly: bool) -> HWND {
    let class = wide("RICHEDIT50W");
    let empty = wide("");
    let mut style = WS_CHILD.0 | WS_VSCROLL.0 | WS_CLIPSIBLINGS.0 | WS_TABSTOP.0;
    style |= (ES_MULTILINE | ES_AUTOVSCROLL | ES_NOHIDESEL) as u32;
    // ES_NOOLEDRAGDROP: the control does not register as an OLE drag-and-drop target
    // (RTF and OLE objects could arrive via drag and drop).
    style |= 0x0000_0008;
    // ES_DISABLENOSCROLL: the scroll bar is always present (disabled when not needed).
    // Otherwise it appears after a long document loads, the text width shrinks,
    // while tables (code blocks, rules) keep their previous width.
    style |= 0x0000_2000;
    if readonly {
        style |= ES_READONLY as u32;
    }
    let hinst = unsafe { GetModuleHandleW(None).ok() };
    let hwnd = unsafe {
        CreateWindowExW(
            WINDOW_EX_STYLE(0),
            PCWSTR::from_raw(class.as_ptr()),
            PCWSTR::from_raw(empty.as_ptr()),
            WINDOW_STYLE(style),
            0,
            0,
            10,
            10,
            Some(parent),
            Some(HMENU(id as *mut core::ffi::c_void)),
            hinst.map(|h| h.into()),
            None,
        )
    }
    .unwrap_or_default();
    if hwnd.0.is_null() {
        return hwnd;
    }
    // No 32K character limit.
    send(hwnd, EM_EXLIMITTEXT, 0, 0x7FFF_FFFE);
    // No URL auto-detection: we manage links ourselves (policy in links.rs).
    send(hwnd, EM_AUTOURLDETECT, 0, 0);
    // Do not switch the keyboard layout and font "by text language".
    let lang = send(hwnd, EM_GETLANGOPTIONS, 0, 0) as u32;
    let lang = lang & !(IMF_AUTOKEYBOARD | IMF_AUTOFONT | IMF_DUALFONT | IMF_AUTOFONTSIZEADJUST);
    send(hwnd, EM_SETLANGOPTIONS, 0, lang as isize);
    send(hwnd, EM_SETTYPOGRAPHYOPTIONS, TO_ADVANCEDTYPOGRAPHY as usize, TO_ADVANCEDTYPOGRAPHY as isize);
    // Protection against OLE objects with links (KB5032314): do not convert linked objects.
    send(hwnd, EM_SETDISABLEOLELINKCONVERSION, 1, 0);
    hwnd
}

pub fn set_readonly(hwnd: HWND, ro: bool) {
    send(hwnd, EM_SETREADONLY, ro as usize, 0);
}

/// Load RTF (generated by us, see render.rs). `selection` — replace the selection.
pub fn set_rtf(hwnd: HWND, rtf: &str, selection: bool) {
    let mut bytes = Vec::with_capacity(rtf.len() + 1);
    bytes.extend_from_slice(rtf.as_bytes());
    bytes.push(0);
    let st = SETTEXTEX { flags: if selection { ST_SELECTION | ST_KEEPUNDO } else { ST_DEFAULT }, codepage: 65001 };
    send(hwnd, EM_SETTEXTEX, &st as *const _ as usize, bytes.as_ptr() as isize);
}

/// Insert RTF at position `at` via TOM (does not touch the selection and does not scroll).
/// A read-only control is unlocked for the duration of the insert. false — it failed.
pub fn insert_rtf(hwnd: HWND, at: i32, rtf: &str) -> bool {
    use windows::Win32::UI::Controls::RichEdit::{ITextRange2, tomConvertRTF};
    let ro = unsafe { windows::Win32::UI::WindowsAndMessaging::GetWindowLongW(hwnd, windows::Win32::UI::WindowsAndMessaging::GWL_STYLE) } as u32 & ES_READONLY as u32 != 0;
    if ro {
        set_readonly(hwnd, false);
    }
    let mut done = false;
    if let Some(doc) = tom(hwnd) {
        unsafe {
            if let Ok(r2) = doc.Range(at, at).and_then(|r| r.cast::<ITextRange2>()) {
                done = r2.SetText2(tomConvertRTF.0, &windows::core::BSTR::from(rtf)).is_ok();
            }
        }
    }
    if ro {
        set_readonly(hwnd, true);
    }
    done
}

/// Replace all text with plain text. Clears the undo history.
///
/// Security: EM_SETTEXTEX/EM_REPLACESEL recognize text starting with `{\rtf`
/// as RTF — a document could inject RTF into the editor (fields, OLE objects). Therefore
/// document text is set only via TOM `ITextRange::SetText` (always plain text).
pub fn set_plain_text(hwnd: HWND, text: &str) {
    if let Some(doc) = tom(hwnd) {
        unsafe {
            if let Ok(r) = doc.Range(0, 0) {
                let _ = r.Expand(tomStory.0);
                if r.SetText(&windows::core::BSTR::from(text)).is_ok() {
                    send(hwnd, EM_EMPTYUNDOBUFFER, 0, 0);
                    return;
                }
            }
        }
    }
    // Fallback path — only for text that cannot be mistaken for RTF.
    let safe = neutralize_rtf_signature(text);
    let w = wide(&safe);
    let st = SETTEXTEX { flags: ST_DEFAULT | ST_UNICODE, codepage: 1200 };
    send(hwnd, EM_SETTEXTEX, &st as *const _ as usize, w.as_ptr() as isize);
    send(hwnd, EM_EMPTYUNDOBUFFER, 0, 0);
}

/// If the text starts with "{" (RTF signatures vary: \rtf, \urtf, \pwd…), insert an
/// invisible character before it (only for the fallback path, when TOM is unavailable).
fn neutralize_rtf_signature(text: &str) -> String {
    if text.trim_start().starts_with('{') {
        format!("\u{2060}{text}")
    } else {
        text.to_string()
    }
}

pub fn text_len(hwnd: HWND) -> i32 {
    let gl = GETTEXTLENGTHEX { flags: GTL_NUMCHARS | GTL_PRECISE, codepage: 1200 };
    send(hwnd, EM_GETTEXTLENGTHEX, &gl as *const _ as usize, 0) as i32
}

/// All text exactly as in the control's memory (GT_RAWTEXT): index = character position (cp),
/// including table structure characters and hidden text. Line breaks are '\r'.
pub fn get_text(hwnd: HWND) -> Vec<u16> {
    let len = text_len(hwnd).max(0) as usize;
    let mut buf = vec![0u16; len + 1];
    let gt = GETTEXTEX {
        cb: ((len + 1) * 2) as u32,
        flags: GT_RAWTEXT,
        codepage: 1200,
        lpDefaultChar: windows::core::PCSTR::null(),
        lpUsedDefChar: std::ptr::null_mut(),
    };
    let n = send(hwnd, EM_GETTEXTEX, &gt as *const _ as usize, buf.as_mut_ptr() as isize).max(0) as usize;
    buf.truncate(n.min(len));
    buf
}

pub fn get_selected_text(hwnd: HWND) -> Vec<u16> {
    let (a, b) = get_sel(hwnd);
    get_range(hwnd, a, b)
}

pub fn get_range(hwnd: HWND, a: i32, b: i32) -> Vec<u16> {
    if b <= a {
        return Vec::new();
    }
    let mut buf = vec![0u16; (b - a) as usize + 1];
    let mut tr = TEXTRANGEW { chrg: CHARRANGE { cpMin: a, cpMax: b }, lpstrText: PWSTR(buf.as_mut_ptr()) };
    let n = send(hwnd, EM_GETTEXTRANGE, 0, &mut tr as *mut _ as isize).max(0) as usize;
    buf.truncate(n);
    buf
}

