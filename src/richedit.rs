/// Margins around the text inside the control.
/// Text margins, px "before zoom": RichEdit multiplies them by the zoom (EM_SETZOOM).
///
/// Top/bottom via EM_SETRECT, left/right via EM_SETMARGINS: at zoom < 100% the margins
/// "before zoom" can be wider than the window itself; EM_SETRECT rejects such a rectangle
/// (resets the margins), while EM_SETMARGINS accepts it (test richedit_layout_assumptions).
pub fn set_margins(hwnd: HWND, left: i32, top: i32, right: i32, bottom: i32) {
    let mut rc = RECT::default();
    unsafe {
        let _ = GetClientRect(hwnd, &mut rc);
    }
    let (left, right) = (left.clamp(0, 0xFFFF), right.clamp(0, 0xFFFF));
    let want = RECT { left: rc.left + left, top: rc.top + top, right: rc.right - right, bottom: (rc.bottom - bottom).max(rc.top + top + 1) };
    // Any margin change re-wraps all the text (tens of ms on a large document
    // on every mode switch). Skip if they have not changed.
    let cur = get_rect(hwnd);
    if cur == want {
        return;
    }
    if cur.top != want.top || cur.bottom != want.bottom {
        let r = RECT { left: rc.left, top: want.top, right: rc.right, bottom: want.bottom };
        send(hwnd, EM_SETRECT, 0, &r as *const _ as isize);
    }
    // EM_SETMARGINS, EC_LEFTMARGIN | EC_RIGHTMARGIN
    send(hwnd, 0x00D3, 3, (((right as u32) << 16) | left as u32) as isize);
    // Unlike EM_SETRECT, EM_SETMARGINS does not repaint the area outside the new text
    // rectangle: the old layout stayed there and the text looked duplicated side by side
    // (Visual mode, toggling the column width). Repaint the whole control.
    unsafe {
        let _ = InvalidateRect(Some(hwnd), None, true);
    }
}

pub fn get_rect(hwnd: HWND) -> RECT {
    let mut r = RECT::default();
    send(hwnd, EM_GETRECT, 0, &mut r as *mut _ as isize);
    r
}

pub fn set_zoom(hwnd: HWND, percent: u32) {
    if percent == 100 {
        send(hwnd, EM_SETZOOM, 0, 0);
    } else {
        send(hwnd, EM_SETZOOM, percent as usize, 100);
    }
}

pub fn get_zoom(hwnd: HWND) -> u32 {
    let mut num: i32 = 0;
    let mut den: i32 = 0;
    send(hwnd, EM_GETZOOM, &mut num as *mut _ as usize, &mut den as *mut _ as isize);
    if num <= 0 || den <= 0 {
        100
    } else {
        (num as i64 * 100 / den as i64) as u32
    }
}

/// Replace the selection with plain text (recorded in the undo history).
/// Via TOM, so that a paste starting with `{\rtf` is not parsed as RTF.
pub fn replace_sel(hwnd: HWND, text: &str, undoable: bool) {
    if let Some(doc) = tom(hwnd) {
        unsafe {
            if let Ok(sel) = doc.GetSelection() {
                if sel.SetText(&windows::core::BSTR::from(text)).is_ok() {
                    let _ = sel.Collapse(0); // tomEnd: caret after the inserted text
                    return;
                }
            }
        }
    }
    let safe = neutralize_rtf_signature(text);
    let w = wide(&safe);
    send(hwnd, EM_REPLACESEL, undoable as usize, w.as_ptr() as isize);
}

pub fn set_event_mask(hwnd: HWND, mask: u32) -> u32 {
    send(hwnd, EM_SETEVENTMASK, 0, mask as isize) as u32
}

pub fn tom(hwnd: HWND) -> Option<ITextDocument> {
    let mut p: *mut core::ffi::c_void = std::ptr::null_mut();
    send(hwnd, EM_GETOLEINTERFACE, 0, &mut p as *mut _ as isize);
    if p.is_null() {
        return None;
    }
    let ole = unsafe { IRichEditOle::from_raw(p) };
    ole.cast::<ITextDocument>().ok()
}

pub fn find_text(hwnd: HWND, needle: &str, from: i32, forward: bool, match_case: bool) -> Option<(i32, i32)> {
    let w = wide(needle);
    let len = text_len(hwnd);
    let mut ft = FINDTEXTEXW {
        chrg: if forward { CHARRANGE { cpMin: from, cpMax: len } } else { CHARRANGE { cpMin: from, cpMax: 0 } },
        lpstrText: PCWSTR::from_raw(w.as_ptr()),
        chrgText: CHARRANGE::default(),
    };
    let mut flags: u32 = 0;
    if forward {
        flags |= 1; // FR_DOWN
    }
    if match_case {
        flags |= 4; // FR_MATCHCASE
    }
    let r = send(hwnd, EM_FINDTEXTEXW, flags as usize, &mut ft as *mut _ as isize);
    if r < 0 {
        None
    } else {
        Some((ft.chrgText.cpMin, ft.chrgText.cpMax))
    }
}

pub fn scroll_scrollcaret_top(hwnd: HWND, cp: i32) {
    // Put position cp at the top of the window.
    set_sel(hwnd, cp, cp);
    let (_, y) = pos_from_char(hwnd, cp);
    let (sx, sy) = scroll_pos(hwnd);
    let rc = get_rect(hwnd);
    set_scroll_pos(hwnd, sx, (sy + y - rc.top - 8).max(0));
}

